export const BASE_AWAKENINGS = Object.freeze(Object.fromEntries(
  BASE_ROWS.map((row) => [row[0], ability('base', ...row)]),
));

export const FUSION_AWAKENINGS = Object.freeze(Object.fromEntries(
  FUSION_ROWS.map((row) => [row[0], ability('fusion', ...row)]),
));

export const AWAKENING_ABILITIES = Object.freeze([
  ...Object.values(BASE_AWAKENINGS),
  ...Object.values(FUSION_AWAKENINGS),
]);

export function awakeningForUnit(unit) {
  if (!unit) return null;
  return unit.specialForm
    ? FUSION_AWAKENINGS[unit.specialForm] ?? null
    : BASE_AWAKENINGS[unit.baseMonsterName] ?? null;
}

export function awakeningById(id) {
  return AWAKENING_ABILITIES.find((entry) => entry.id === id) ?? null;
}

